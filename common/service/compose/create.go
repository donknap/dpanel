func WithYamlPath(path string) cli.ProjectOptionsFn {
	return func(options *cli.ProjectOptions) error {
		options.ConfigPaths = append(options.ConfigPaths, path)
		return nil
	}
}

func WithYamlContent(content ...string) cli.ProjectOptionsFn {
	return func(options *cli.ProjectOptions) error {
		if !function.IsEmptyArray(options.ConfigPaths) {
			return errors.New("already configured yaml file path")
		}
		tempPath, _ := storage.Local{}.CreateTempDir("")
		tempEnvFile := filepath.Join(tempPath, ".env")
		for i, c := range content {
			tempComposeFile := filepath.Join(tempPath, fmt.Sprintf("compose.%d.yaml", i))
			err := os.WriteFile(
				tempComposeFile,
				append([]byte("# 此文件由 dpanel 面板生成，请勿修改！ \n# Generated by dpanel, do not modify!\n"), []byte(c)...),
				0666,
			)
			if err != nil {
				slog.Debug("compose create withYamlContent", "content", strings.Join(content, ","), "err", err)
				return err
			}
			options.ConfigPaths = append(options.ConfigPaths, tempComposeFile)
		}

		if !function.IsEmptyMap(options.Environment) {
			err := os.WriteFile(tempEnvFile, []byte(strings.Join(options.Environment.Values(), "\n")), 0666)
			if err != nil {
				slog.Debug("compose create withYamlContent", "content", strings.Join(content, ","), "err", err)
				return err
			}
		}

		options.EnvFiles = append(options.EnvFiles, tempEnvFile)
		return nil
	}
}

func NewCompose(ctx context.Context, dockerSdk *docker.Client, options *cli.ProjectOptions) (wrapper *Task, warning, err error) {
	if len(options.ConfigPaths) == 0 {
		return nil, nil, errors.New("compose configuration files are required")
	}
	var loadOptions *loader.Options
	for _, configure := range []cli.ProjectOptionsFn{
		cli.WithExtension(ExtensionServiceName, ExtService{}),
		cli.WithResolvedPaths(false),
		cli.WithLoadOptions(func(options *loader.Options) {
			loadOptions = options
		}),
	} {
		if err := configure(options); err != nil {
			return nil, warning, err
		}
	}
	originalFormatter := logrus.StandardLogger().Formatter
	originalOutput := logrus.StandardLogger().Out
	bufOut := new(bytes.Buffer)
	logrus.SetOutput(bufOut)
	logrus.SetFormatter(&logrus.JSONFormatter{
		PrettyPrint:       false,
		DisableTimestamp:  true,
		DisableHTMLEscape: true,
	})
	defer func() {
		logrus.SetOutput(originalOutput)
		logrus.SetFormatter(originalFormatter)
	}()
	workingDir := options.WorkingDir
	sourceDir := filepath.Dir(options.ConfigPaths[0])
	options.WorkingDir = sourceDir
	model, err := options.LoadModel(ctx)
	options.WorkingDir = workingDir
	if err != nil {
		return nil, warning, err
	}
	resources := make(map[string]any)
	if services, ok := model["services"].(map[string]any); ok {
		for name, value := range services {
			service, ok := value.(map[string]any)
			if !ok {
				return nil, warning, fmt.Errorf("invalid compose service %q", name)
			}
			files := make(map[string]any)
			for _, key := range []string{"env_file", "label_file"} {
				if value, ok := service[key]; ok {
					files[key] = value
				}
			}
			resources[name] = files
		}
	}
	if err := paths.ResolveRelativePaths(map[string]any{"services": resources}, sourceDir, nil); err != nil {
		return nil, warning, err
	}
	project, err := loader.ModelToProject(model, loadOptions, types.ConfigDetails{
		WorkingDir:  workingDir,
		Environment: options.Environment,
	})
	if err != nil {
		return nil, warning, err
	}
	project.ComposeFiles = append([]string(nil), options.ConfigPaths...)

	if bufOut.Len() > 0 {
		msg := make([]string, 0)
		var data map[string]string
		reader := bufio.NewReader(bufOut)
		for {
			line, _, err := reader.ReadLine()
			if err != nil {
				break
			}
			if err = json.Unmarshal(line, &data); err == nil && data["level"] != "debug" {
				msg = append(msg, data["msg"])
			}
		}
		warning = errors.New(strings.Join(msg, ", \n"))
	}

	wrapper = &Task{
		dockerSdk:    dockerSdk,
		Name:         project.Name,
		Project:      project,
		ComposeFiles: project.ComposeFiles,
		WorkingDir:   project.WorkingDir,
	}
	return wrapper, warning, nil
}
